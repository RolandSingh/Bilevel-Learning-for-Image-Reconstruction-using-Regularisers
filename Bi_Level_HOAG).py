import numpy as np

rng = np.random.default_rng(0)

N, H, W = 2, 8, 8          # 2 images, 8x8  (full-batch tensor [N,H,W])
KS, SIG = 5, 1.0
MU = 1e-2                   # ridge -> strict strong convexity for the check


def gaussian_kernel(ks, sig):
    ax = np.arange(ks) - (ks - 1) / 2.0
    xx, yy = np.meshgrid(ax, ax, indexing="ij")
    k = np.exp(-(xx**2 + yy**2) / (2 * sig**2))
    return k / k.sum()

K = gaussian_kernel(KS, SIG)
P = KS // 2

# ---- A via spatial circular correlation (matches torch circular-pad conv2d) ----
def A_spatial(x):
    out = np.zeros_like(x)
    for a in range(KS):
        for b in range(KS):
            sa, sb = a - P, b - P
            out += K[a, b] * np.roll(x, shift=(-sa, -sb), axis=(-2, -1))
    return out

# ---- A via FFT OTF (matches the script's A_dagger construction) ----
def build_otf():
    psf = np.zeros((H, W))
    psf[:KS, :KS] = K
    psf = np.roll(psf, shift=(-(KS // 2), -(KS // 2)), axis=(0, 1))
    return np.fft.fft2(psf)

OTF = build_otf()
def A_fft(x):
    return np.real(np.fft.ifft2(OTF[None] * np.fft.fft2(x)))

# (1) self-adjointness
u, v = rng.standard_normal((N, H, W)), rng.standard_normal((N, H, W))
lhs, rhs = np.sum(A_spatial(u) * v), np.sum(u * A_spatial(v))
print(f"(1) self-adjoint  <Au,v>={lhs:.6f}  <u,Av>={rhs:.6f}  "
      f"rel.diff={abs(lhs-rhs)/abs(lhs):.2e}")

# (2) spatial vs FFT operator
d = np.abs(A_spatial(u) - A_fft(u)).max()
print(f"(2) spatial vs FFT operator  max|diff|={d:.2e}")

A = A_spatial  # use the spatial (conv-equivalent) operator from here on

# ---------------- data ----------------
x_clean = np.clip(rng.uniform(0, 1, (N, H, W)), 0, 1)
y = A(x_clean) + 0.01 * rng.standard_normal((N, H, W))

# ---------------- smoothed-TV Phi, analytic grad / HVP / cross ----------------
def tv_terms(x):
    dh = np.roll(x, -1, axis=-2) - x
    dv = np.roll(x, -1, axis=-1) - x
    return dh, dv

def Phi(x, theta):
    lam, eps = np.exp(theta[0]), np.exp(theta[1])
    dh, dv = tv_terms(x)
    tv = np.sqrt(dh**2 + dv**2 + eps).sum()
    return 0.5*np.sum((y - A(x))**2) + lam*tv + 0.5*MU*np.sum(x**2)

def grad_x(x, theta):
    lam, eps = np.exp(theta[0]), np.exp(theta[1])
    dh, dv = tv_terms(x)
    w = 1.0/np.sqrt(dh**2 + dv**2 + eps)
    a, c = dh*w, dv*w
    # adjoints of forward-difference operators: D^T z = roll(z,+1) - z
    dtv = (np.roll(a, 1, axis=-2) - a) + (np.roll(c, 1, axis=-1) - c)
    return A(A(x) - y) + lam*dtv + MU*x      # A self-adjoint -> A^T = A

def hvp(x, theta, vvec, h=1e-5):            # numerical Hessian-vector product
    return (grad_x(x + h*vvec, theta) - grad_x(x - h*vvec, theta)) / (2*h)

def cg(matvec, b, iters=400, tol=1e-12):
    q = np.zeros_like(b); r = b.copy(); p = r.copy(); rs = np.sum(r*r)
    for _ in range(iters):
        if np.sqrt(rs) < tol: break
        Hp = matvec(p); alpha = rs/np.sum(p*Hp)
        q += alpha*p; r -= alpha*Hp; rs_new = np.sum(r*r)
        p = r + (rs_new/rs)*p; rs = rs_new
    return q

def solve_inner(theta, newton_steps=12):     # accurate x*(theta) via Newton-CG
    x = y.copy()
    for _ in range(newton_steps):
        g = grad_x(x, theta)
        delta = cg(lambda vv: hvp(x, theta, vv), g)
        x = x - delta
    return x

def upper(x):  return np.mean((x - x_clean)**2)
def J(theta):  return upper(solve_inner(theta))

# ---------------- HOAG hypergradient (same steps as the Torch script) --------
def hoag_hypergrad(theta):
    xs = solve_inner(theta)
    b = (2.0/x_clean.size)*(xs - x_clean)            # grad_x upper
    q = cg(lambda vv: hvp(xs, theta, vv), b)          # H^{-1} b
    # hyper = - d/dtheta ( grad_x(xs,theta)^T q ), q held fixed
    eps_fd = 1e-5; g = np.zeros(2)
    for j in range(2):
        tp, tm = theta.copy(), theta.copy()
        tp[j] += eps_fd; tm[j] -= eps_fd
        sp = np.sum(grad_x(xs, tp)*q); sm = np.sum(grad_x(xs, tm)*q)
        g[j] = -(sp - sm)/(2*eps_fd)
    return g

theta0 = np.array([np.log(5e-3), np.log(1e-2)])
hg = hoag_hypergrad(theta0)

# finite-difference of the TRUE outer loss J(theta)
fd = np.zeros(2); e = 1e-4
for j in range(2):
    tp, tm = theta0.copy(), theta0.copy()
    tp[j] += e; tm[j] -= e
    fd[j] = (J(tp) - J(tm))/(2*e)

