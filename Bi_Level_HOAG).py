# ============================================================================
# HOAG HYPERGRADIENT  (Algorithm 2; b = grad of the MSE)
# ============================================================================
def hoag_hypergradient(theta, eps_tol, q_warm=None):
    x_star, inner_gnorm = solve_inner(theta, eps_tol)

    xb = x_star.detach().clone().requires_grad_(True)
    J = upper_loss(xb)
    b = torch.autograd.grad(J, xb)[0]                       # b = grad_x MSE

    hvp = make_hvp(x_star, theta)
    q = conjugate_gradient(hvp, b, Cfg.CG_MAX_ITER, eps_tol, warm_start=q_warm)

    xc = x_star.detach().clone().requires_grad_(True)
    tc = theta.detach().clone().requires_grad_(True)
    grad_x = torch.autograd.grad(Phi(xc, tc), xc, create_graph=True)[0]
    cross = torch.autograd.grad((grad_x * q.detach()).sum(), tc)[0]   # (d^2Phi/dxdtheta)^T q
    hyper_grad = -cross

    return hyper_grad.detach(), J.item(), x_star, q, inner_gnorm


# ============================================================================
# OUTER OPTIMIZATION LOOP
# ============================================================================
def run_hoag():
    theta = initialize_theta(Cfg.DEVICE).requires_grad_(True)
    opt = torch.optim.Adam([theta], lr=Cfg.OUTER_LR)

    init_filters = parse_theta(theta)[3].detach().clone()
    eps_tol = Cfg.EPS_TOL_INIT
    q_warm = None
    history = {"mse": [], "global_w": [], "mean_beta": [], "tol": []}

    print("\n" + "=" * 78)
    print(f"{'iter':>4} | {'outer MSE':>11} | {'e^theta0':>10} | {'mean e^beta':>11} | "
          f"{'tol':>8} | {'||g_in||':>9}")
    print("=" * 78)

    for it in range(Cfg.OUTER_STEPS):
        hyper_grad, mse, x_star, q, inner_gnorm = hoag_hypergradient(theta, eps_tol, q_warm)
        q_warm = q

        opt.zero_grad()
        theta.grad = hyper_grad
        opt.step()

        th0, beta, s, _ = parse_theta(theta)
        gw = math.exp(th0.item())
        mb = torch.exp(beta).mean().item()
        history["mse"].append(mse)
        history["global_w"].append(gw)
        history["mean_beta"].append(mb)
        history["tol"].append(eps_tol)

        if it % 2 == 0 or it == Cfg.OUTER_STEPS - 1:
            print(f"{it:>4} | {mse:>11.6f} | {gw:>10.4f} | {mb:>11.5f} | "
                  f"{eps_tol:>8.1e} | {inner_gnorm:>9.2e}")

        eps_tol = max(eps_tol * Cfg.EPS_DECAY, 1e-10)

    # final, high-accuracy reconstruction at the learned regularizer
    x_final, _ = solve_inner(theta.detach(), eps_tol=1e-6, max_steps=Cfg.INNER_STEPS_FINAL)
    learned_filters = parse_theta(theta)[3].detach().clone()
    return theta.detach(), x_final, history, init_filters, learned_filters


theta_star, x_recon, hist, init_filters, learned_filters = run_hoag()


