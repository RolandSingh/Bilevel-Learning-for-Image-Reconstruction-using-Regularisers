def psnr(a: torch.Tensor, b: torch.Tensor) -> float:
    mse = ((a.clamp(0, 1) - b.clamp(0, 1)) ** 2).mean().item()
    return 10.0 * math.log10(1.0 / max(mse, 1e-12))


