def gaussian_kernel(ksize: int, sigma: float, device) -> torch.Tensor:
    ax = torch.arange(ksize, dtype=torch.float32, device=device) - (ksize - 1) / 2.0
    xx, yy = torch.meshgrid(ax, ax, indexing="ij")
    k = torch.exp(-(xx ** 2 + yy ** 2) / (2.0 * sigma ** 2))
    k = k / k.sum()                      # normalize -> preserves image mean
    return k                             # [ksize, ksize]


_KERNEL = gaussian_kernel(Cfg.BLUR_KSIZE, Cfg.BLUR_SIGMA, Cfg.DEVICE)
_KERNEL4 = _KERNEL.view(1, 1, Cfg.BLUR_KSIZE, Cfg.BLUR_KSIZE)
_PAD = Cfg.BLUR_KSIZE // 2


def A(x: torch.Tensor) -> torch.Tensor:
    """Apply the Gaussian-blur forward operator (circular padding)."""
    xp = F.pad(x, (_PAD, _PAD, _PAD, _PAD), mode="circular")
    return F.conv2d(xp, _KERNEL4)        # symmetric kernel -> A is self-adjoint


# --- Optical transfer function (OTF) for the FFT-based pseudo-inverse init ---
def _build_otf(kernel2d: torch.Tensor, shape, device) -> torch.Tensor:
    """psf2otf: place the kernel with its center at the (0,0) origin (parity-
    robust) so that the FFT operator exactly matches the circular conv A."""
    H, W = shape
    k = kernel2d.shape[0]
    psf = torch.zeros(H, W, device=device)
    psf[:k, :k] = kernel2d                      # kernel center sits at (k//2, k//2)
    psf = torch.roll(psf, shifts=(-(k // 2), -(k // 2)), dims=(0, 1))  # -> (0,0)
    return torch.fft.fft2(psf)                  # OTF, consistent with circular A


_OTF = _build_otf(_KERNEL, (Cfg.IMG_SIZE, Cfg.IMG_SIZE), Cfg.DEVICE)


@torch.no_grad()
def A_dagger(y: torch.Tensor, alpha: float = Cfg.WIENER_ALPHA) -> torch.Tensor:
    """Tikhonov-regularized pseudo-inverse  A^dagger y  =  IFFT( conj(K) Y /
    (|K|^2 + alpha) ).  Used only to warm-start the inner solver."""
    Y = torch.fft.fft2(y)
    X = (torch.conj(_OTF) / (_OTF.abs() ** 2 + alpha)) * Y
    return torch.fft.ifft2(X).real


