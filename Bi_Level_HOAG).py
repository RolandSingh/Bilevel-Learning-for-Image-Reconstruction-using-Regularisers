def get_gaussian_kernel_2d(k_size, sig):
    coords = torch.arange(k_size, dtype=torch.float32) - (k_size - 1) / 2
    Y, X = torch.meshgrid(coords, coords, indexing='ij')
    squared_dist = X**2 + Y**2
    g_2d = torch.exp(-squared_dist / (2 * sig**2))
    return (g_2d / g_2d.sum()).view(1, 1, k_size, k_size).to(Config.DEVICE)

class Physics2D:
    def __init__(self, blur_sigma, noise_sigma, device):
        # FIXED: Matched the paper's exact physics configuration
        self.k_size = 23
        self.padding = self.k_size // 2
        self.kernel = get_gaussian_kernel_2d(self.k_size, blur_sigma).to(device)
        self.noise_sigma = noise_sigma

    def A(self, x):
        padded = F.pad(x, [self.padding]*4, mode='constant', value=0)
        return F.conv2d(padded, self.kernel)

    def A_adjoint(self, y):
        return F.conv_transpose2d(y, self.kernel, padding=self.padding)

    def A_dagger(self, y):
        return y.clone()

    def __call__(self, x):
        return self.A(x) + torch.randn_like(self.A(x)) * self.noise_sigma

def regularizer_only(w, theta):
    theta_0, theta_1 = theta[0], theta[1]
    dh = w[:, :, :, 1:] - w[:, :, :, :-1]
    dv = w[:, :, 1:, :] - w[:, :, :-1, :]
    dh = F.pad(dh, (0, 1, 0, 0))
    dv = F.pad(dv, (0, 0, 0, 1))
    tv_norm = torch.sqrt(dh**2 + dv**2 + torch.exp(theta_1))
    return (torch.exp(theta_0) / w.numel()) * tv_norm.sum()

def inner_loss_func(w, theta, y, physics_op):
    Aw = physics_op.A(w)
    n = y.numel()
    fidelity = (1.0 / n) * torch.sum((y - Aw)**2)
    return fidelity + regularizer_only(w, theta)

