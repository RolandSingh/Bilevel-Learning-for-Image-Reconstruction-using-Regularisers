# ============================================================================
#  5.  REGULARIZER  g_theta  +  LOWER-LEVEL OBJECTIVE  Phi
# ============================================================================
def tv_regularizer(x: torch.Tensor, theta: torch.Tensor) -> torch.Tensor:
    lam = torch.exp(theta[0])
    eps = torch.exp(theta[1])
    dh = torch.roll(x, shifts=-1, dims=2) - x          # vertical differences
    dv = torch.roll(x, shifts=-1, dims=3) - x          # horizontal differences
    tv = torch.sqrt(dh ** 2 + dv ** 2 + eps)
    return lam * tv.sum()


def Phi(x: torch.Tensor, theta: torch.Tensor) -> torch.Tensor:
    """Lower-level objective: 1/2 ||y - A x||^2 + g_theta(x), summed over the
    full batch (separable across images -> joint minimizer == per-image)."""
    data_fidelity = 0.5 * ((y - A(x)) ** 2).sum()
    return data_fidelity + tv_regularizer(x, theta)


def upper_loss(x: torch.Tensor) -> torch.Tensor:
    """Upper-level objective: mean-squared error against the clean images."""
    return ((x - x_clean) ** 2).mean()


# ============================================================================
#  6.  INNER SOLVER
# ============================================================================
def solve_inner(theta: torch.Tensor, eps_tol: float):
    """Approximate x*(theta) = argmin_x Phi(x, theta).
    Stops when the gradient norm drops below (eps_tol * initial gradient norm)
    or after INNER_STEPS iterations -- the HOAG inner-accuracy criterion."""
    x = A_dagger(y).clamp(0.0, 1.0).detach().clone().requires_grad_(True)  # x0 = A^dagger y

    opt = torch.optim.Adam([x], lr=Cfg.INNER_LR)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(
        opt, T_max=Cfg.INNER_STEPS, eta_min=Cfg.INNER_LR * 0.01)

    # reference gradient norm at the starting point (for a relative tolerance)
    g0 = torch.autograd.grad(Phi(x, theta.detach()), x)[0].norm().item()
    g0 = max(g0, 1e-12)
    stop = eps_tol * g0

    last_gnorm = g0
    for _ in range(Cfg.INNER_STEPS):
        opt.zero_grad()
        loss = Phi(x, theta.detach())
        loss.backward()
        last_gnorm = x.grad.norm().item()
        opt.step()
        sched.step()
        if last_gnorm < stop:
            break
    return x.detach(), last_gnorm


# ============================================================================
#  7.  HESSIAN-VECTOR PRODUCT  +  CONJUGATE GRADIENT
# ============================================================================
def make_hvp(x_star: torch.Tensor, theta: torch.Tensor):
    """Return a closure v -> H v evaluated at (x_star, theta); the graph for the
    inner gradient is built once and reused across CG iterations."""
    x = x_star.detach().clone().requires_grad_(True)
    grad_x = torch.autograd.grad(Phi(x, theta.detach()), x, create_graph=True)[0]

    def hvp(v: torch.Tensor) -> torch.Tensor:
        Hv = torch.autograd.grad(grad_x, x, grad_outputs=v.detach(),
                                 retain_graph=True)[0]
        return Hv + Cfg.CG_DAMPING * v        # small ridge for CG stability
    return hvp


def conjugate_gradient(hvp, b: torch.Tensor, max_iter: int, tol: float,
                       warm_start=None):
    """Solve H q = b for q using Conjugate Gradient (matrix-free)."""
    if warm_start is not None and warm_start.shape == b.shape:
        q = warm_start.detach().clone()
        r = b - hvp(q)
    else:
        q = torch.zeros_like(b)
        r = b.clone()
    p = r.clone()
    rs_old = (r * r).sum()
    b_norm = b.norm().item()
    thresh = tol * b_norm

    for _ in range(max_iter):
        if math.sqrt(rs_old.item()) < thresh:
            break
        Hp = hvp(p)
        pHp = (p * Hp).sum()
        if pHp.abs().item() < 1e-16:
            break
        alpha = rs_old / pHp
        q = q + alpha * p
        r = r - alpha * Hp
        rs_new = (r * r).sum()
        p = r + (rs_new / rs_old) * p
        rs_old = rs_new
    return q.detach()


# ============================================================================
#  8.  HOAG HYPERGRADIENT COMPUTATION
# ============================================================================
def hoag_hypergradient(theta, eps_tol, q_warm=None):
    # (1) inner solve to tolerance eps_tol
    x_star, inner_gnorm = solve_inner(theta, eps_tol)

    # (2) gradient of the UPPER objective w.r.t. the reconstruction
    xb = x_star.detach().clone().requires_grad_(True)
    J = upper_loss(xb)
    b = torch.autograd.grad(J, xb)[0]

    # (3) invert the inner Hessian against b with CG  ->  q = H^{-1} b
    hvp = make_hvp(x_star, theta)
    q = conjugate_gradient(hvp, b, Cfg.CG_MAX_ITER, eps_tol, warm_start=q_warm)

    # (4) mixed-partial contraction  ->  approximate hypergradient
    xc = x_star.detach().clone().requires_grad_(True)
    tc = theta.detach().clone().requires_grad_(True)
    grad_x = torch.autograd.grad(Phi(xc, tc), xc, create_graph=True)[0]
    cross = torch.autograd.grad((grad_x * q.detach()).sum(), tc)[0]
    hyper_grad = -cross

    return hyper_grad.detach(), J.item(), x_star, q, inner_gnorm


