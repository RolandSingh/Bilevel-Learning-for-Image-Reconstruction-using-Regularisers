    g0 = torch.autograd.grad(Phi(x, theta.detach()), x)[0].norm().item()
    g0 = max(g0, 1e-12)
    stop = eps_tol * g0

    last_gnorm = g0
    for _ in range(max_steps):
        opt.zero_grad()
