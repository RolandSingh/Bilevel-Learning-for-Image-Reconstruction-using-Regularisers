# 5. HOAG CORE
# ==========================================
class HOAGState:
    def __init__(self, init_tol, dec_type, dec_factor):
        self.epsilon_tol = init_tol
        self.dec_type = dec_type
        self.dec_factor = dec_factor
        self.q_warmstart = None

    def decrease_tolerance(self):
        if self.dec_type == 'exponential': self.epsilon_tol *= self.dec_factor
        self.epsilon_tol = max(self.epsilon_tol, 1e-12)

def solve_inner_problem(w_init, theta, y, physics_op, inner_loss_fn, state, lr, max_steps):
    w = w_init.detach().clone().requires_grad_(True)
    optimizer = torch.optim.Adam([w], lr=lr)

    # ADDED: Cosine Annealing to ensure smooth pixel convergence
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=max_steps, eta_min=lr * 0.01)

    with torch.enable_grad():
        loss_init = inner_loss_fn(w, theta.detach(), y, physics_op)
        grad_init = autograd.grad(loss_init, w)[0]
        norm_init = max(grad_init.norm().item(), 1e-12)

    stop_threshold = state.epsilon_tol * norm_init

    for step in range(max_steps):
        optimizer.zero_grad()
        loss = inner_loss_fn(w, theta.detach(), y, physics_op)
        loss.backward()
        if w.grad.norm().item() < stop_threshold: break
        optimizer.step()
        scheduler.step() # Step the scheduler

    return w

def hoag_step(theta, y, img_true, physics_op, inner_loss_fn, state, inner_lr, inner_steps, cg_max_iter):
    w_init = physics_op.A_dagger(y).detach().clone().clamp(0, 1)
    w_star = solve_inner_problem(w_init, theta, y, physics_op, inner_loss_fn, state, inner_lr, inner_steps)

    w_star = w_star.detach().requires_grad_(True)

    # UPPER LEVEL LOSS: Mean Squared Error
    val_loss = F.mse_loss(w_star.clamp(0, 1), img_true)

    # Compute Gradient of Upper Level Loss w.r.t w_star
    val_loss_grad_w = autograd.grad(val_loss, w_star, retain_graph=True)[0]

    q = conjugate_gradient(inner_loss_fn, w_star, theta, y, physics_op, b=val_loss_grad_w,
                           max_iter=cg_max_iter, tol=state.epsilon_tol, warm_start=state.q_warmstart)
    state.q_warmstart = q.detach().clone()

    w_cross = w_star.detach().requires_grad_(True)
    th_cross = theta.detach().requires_grad_(True)

    with torch.enable_grad():
        loss_cross = inner_loss_fn(w_cross, th_cross, y, physics_op)
        grad_w_cross = autograd.grad(loss_cross, w_cross, create_graph=True)[0]
        grad_dot_q = torch.sum(grad_w_cross * q.detach())
        cross_grad_theta = autograd.grad(grad_dot_q, th_cross)[0]

    return -cross_grad_theta.detach(), val_loss.item(), w_star

